const crypto = require('crypto');
const prisma = require('../../config/db');
const { getConfig } = require('../../utils/configHelper');

const getFrontendUrl = async () => {
    return (await getConfig('frontend_url')) || process.env.FRONTEND_URL || 'http://localhost:9002';
};

const generateInviteKey = () => crypto.randomBytes(12).toString('hex');

exports.createNFCCardIssuance = async (req, res) => {
    try {
        const { orderId } = req.params;
        const {
            nfcCardNumber,
            method = 'taptoinvite_site',
            calendarUrl,
            locationUrl,
            digitalInvitationType,
            digitalInvitationContent,
            websiteUrl,
            websiteEnabled = true,
            googleCalendarLink,
            calendarEnabled = true,
            locationEnabled = true,
            digitalInvitationEnabled = true,
            status = 'registered',
        } = req.body;

        if (!orderId || !nfcCardNumber) {
            return res.status(400).json({ success: false, message: 'Order ID and NFC card number are required.' });
        }

        const order = await prisma.order.findUnique({
            where: { id: parseInt(orderId) },
            select: { id: true, order_number: true }
        });

        if (!order) {
            return res.status(404).json({ success: false, message: 'Order not found.' });
        }

        const frontendUrl = await getFrontendUrl();
        const autogeneratedKey = generateInviteKey();
        const generatedUrl = `${frontendUrl}/invite/${autogeneratedKey}`;

        const issuance = await prisma.nFCCardIssuance.create({
            data: {
                order_id: order.id,
                nfc_card_number: String(nfcCardNumber).trim(),
                autogenerated_key: autogeneratedKey,
                generated_url: generatedUrl,
                method: String(method),
                calendar_url: calendarUrl || null,
                calendar_enabled: Boolean(calendarEnabled),
                location_url: locationUrl || null,
                location_enabled: Boolean(locationEnabled),
                digital_invitation_type: digitalInvitationType || null,
                digital_invitation_content: digitalInvitationContent || null,
                digital_invitation_enabled: Boolean(digitalInvitationEnabled),
                website_url: websiteUrl || null,
                website_enabled: Boolean(websiteEnabled),
                google_calendar_link: googleCalendarLink || null,
                status: String(status),
            },
        });

        res.status(201).json({
            success: true,
            message: 'Card registered successfully',
            data: {
                id: issuance.id,
                orderId: order.id,
                orderNumber: order.order_number,
                nfcCardNumber: issuance.nfc_card_number,
                autogeneratedKey: issuance.autogenerated_key,
                generatedUrl: issuance.generated_url,
                method: issuance.method,
                status: issuance.status,
            },
        });
    } catch (error) {
        console.error('Create NFC Issuance Error:', error);
        res.status(500).json({ success: false, message: 'Failed to register NFC card', error: error.message });
    }
};

