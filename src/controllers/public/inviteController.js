const prisma = require('../../config/db');
const { getConfig } = require('../../utils/configHelper');

const buildInvitePayload = (issuance, frontendUrl) => {
    const order = issuance.order;
    const categoryName = order?.category?.name || 'Event';
    const planName = order?.plan?.name || 'Invitation Plan';

    const features = {
        calendar: {
            enabled: Boolean(issuance.calendar_url),
            url: issuance.calendar_url || null,
        },
        location: {
            enabled: Boolean(issuance.location_url),
            url: issuance.location_url || null,
        },
        digitalInvitation: {
            enabled: Boolean(issuance.digital_invitation_content),
            type: issuance.digital_invitation_type || null,
            content: issuance.digital_invitation_content || null,
        },
        website: {
            enabled: Boolean(issuance.website_url),
            url: issuance.website_url || null,
        },
    };

    return {
        key: issuance.autogenerated_key,
        method: issuance.method,
        generatedUrl: issuance.generated_url,
        redirectUrl: issuance.method === 'google_calendar' ? issuance.google_calendar_link || null : null,
        eventDetails: {
            title: order?.event_title || 'TapToInvite Event',
            type: categoryName,
            date: order?.event_date,
            location: issuance.location_url || null,
            description: order?.digital_notes || '',
            backgroundImage: `/invite-${String(categoryName).toLowerCase().replace(/\s+/g, '-')}.jpg`,
        },
        orderSummary: {
            orderNumber: order?.order_number,
            planName,
            categoryName,
        },
        features,
        trackingNotes: (order?.tracking_notes || [])
            .filter((note) => note.visible_to_user)
            .map((note) => ({
                id: note.id,
                heading: note.heading,
                description: note.description,
                noteDate: note.note_date,
                noteTime: note.note_time,
            })),
        frontendUrl,
    };
};

exports.getPublicInviteByKey = async (req, res) => {
    try {
        const { key } = req.params;

        if (!key) {
            return res.status(400).json({ success: false, message: 'Invite key is required.' });
        }

        const issuance = await prisma.nFCCardIssuance.findUnique({
            where: { autogenerated_key: key },
            include: {
                order: {
                    include: {
                        plan: { select: { name: true } },
                        category: { select: { name: true } },
                        tracking_notes: {
                            orderBy: { created_at: 'desc' },
                        },
                    },
                },
            },
        });

        if (!issuance) {
            return res.status(404).json({ success: false, message: 'Invitation link not found.' });
        }

        const frontendUrl = (await getConfig('frontend_url')) || process.env.FRONTEND_URL || 'http://localhost:9002';

        res.status(200).json({
            success: true,
            message: 'Invitation fetched successfully',
            data: buildInvitePayload(issuance, frontendUrl),
        });
    } catch (error) {
        console.error('Get Public Invite Error:', error);
        res.status(500).json({ success: false, message: 'Failed to fetch invitation link', error: error.message });
    }
};
